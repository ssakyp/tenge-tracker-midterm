-- 500 transactions spread across the 100 accounts and the last year.
-- Transfer rows point to a different existing account.
INSERT INTO transactions
    (account_id, category_id, amount, type, target_account_id, description, "date")
SELECT
    1 + ((n * 7) % 100) AS account_id,
    1 + ((n * 3) % 8) AS category_id,
    (500 + ((n * 1379) % 75000))::numeric(15,2) AS amount,
    CASE
        WHEN n % 10 IN (0, 1) THEN 'INCOME'
        WHEN n % 10 = 2 THEN 'TRANSFER'
        ELSE 'EXPENSE'
    END AS type,
    CASE WHEN n % 10 = 2 THEN 1 + (((n * 7) % 100 + 17) % 100) ELSE NULL END AS target_account_id,
    CASE
        WHEN n % 10 IN (0, 1) THEN 'Demo income #' || n
        WHEN n % 10 = 2 THEN 'Demo transfer #' || n
        ELSE 'Demo expense #' || n
    END AS description,
    CURRENT_DATE - ((n * 13) % 365) AS "date"
FROM generate_series(1, 500) AS series(n);

