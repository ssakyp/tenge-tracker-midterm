    'Demo Account ' || LPAD(n::text, 3, '0'),
    (50000 + ((n * 7919) % 950000))::numeric(15,2),
    CASE WHEN n % 10 = 0 THEN 'USD' WHEN n % 7 = 0 THEN 'EUR' ELSE 'KZT' END
