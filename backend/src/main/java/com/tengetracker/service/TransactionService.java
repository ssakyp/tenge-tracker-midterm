package com.tengetracker.service;

import com.tengetracker.dto.patch.TransactionPatchRequest;
import com.tengetracker.exception.BadRequestException;
import com.tengetracker.exception.ForbiddenException;
import com.tengetracker.exception.ResourceNotFoundException;
import com.tengetracker.model.Account;
import com.tengetracker.model.Category;
import com.tengetracker.model.Tag;
import com.tengetracker.model.Transaction;
import com.tengetracker.repository.AccountRepository;
import com.tengetracker.repository.CategoryRepository;
import com.tengetracker.repository.TagRepository;
import com.tengetracker.repository.TransactionRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

/**
 * Transactions belong to the user who owns their source account.
 * Both the source and the transfer target account must belong to the current user.
 */
@Service
@RequiredArgsConstructor
public class TransactionService {

    private static final Set<String> VALID_TYPES = Set.of("INCOME", "EXPENSE", "TRANSFER");

    private final TransactionRepository transactionRepository;
    private final AccountRepository accountRepository;
    private final CategoryRepository categoryRepository;
    private final TagRepository tagRepository;
    private final AccountService accountService;

    public List<Transaction> getAllTransactions(LocalDate startDate, LocalDate endDate, String type, Long userId) {
        if (startDate != null && endDate != null && startDate.isAfter(endDate)) {
            throw new BadRequestException("startDate must not be after endDate");
        }
        String filterType = null;
        if (type != null && !type.isBlank()) {
            filterType = type.trim().toUpperCase();
            if (!VALID_TYPES.contains(filterType)) {
                throw new BadRequestException("Invalid transaction type: " + type);
            }
        }
        final String typeFilter = filterType;
        return transactionRepository.findByAccount_UserIdOrderByDateDescIdDesc(userId).stream()
                .filter(t -> startDate == null || !t.getDate().isBefore(startDate))
                .filter(t -> endDate == null || !t.getDate().isAfter(endDate))
                .filter(t -> typeFilter == null || t.getType().equals(typeFilter))
                .toList();
    }

    /** 404 if missing, 403 if the transaction's account belongs to someone else. */
    public Transaction getTransactionById(Long id, Long userId) {
        Transaction transaction = transactionRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Transaction not found with id: " + id));
        Account source = accountRepository.findById(transaction.getAccountId())
                .orElseThrow(() -> new ResourceNotFoundException("Account not found: " + transaction.getAccountId()));
        if (!source.getUserId().equals(userId)) {
            throw new ForbiddenException("You do not have access to transaction " + id);
        }
        return transaction;
    }

    /** Transactions where the account is the source or the transfer target. */
    public List<Transaction> getTransactionsByAccount(Long accountId, Long userId) {
        accountService.getAccountById(accountId, userId); // 404 / 403 checks
        return transactionRepository.findByAccountIdOrTargetAccountIdOrderByDateDescIdDesc(accountId, accountId);
    }

    public List<Transaction> getTransactionsByCategory(Long categoryId, Long userId) {
        if (!categoryRepository.existsById(categoryId)) {
            throw new ResourceNotFoundException("Category not found with id: " + categoryId);
        }
        return transactionRepository.findByCategoryIdAndAccount_UserIdOrderByDateDescIdDesc(categoryId, userId);
    }

    public List<Transaction> getTransactionsByTag(Long tagId, Long userId) {
        if (!tagRepository.existsById(tagId)) {
            throw new ResourceNotFoundException("Tag not found with id: " + tagId);
        }
        return transactionRepository.findByTags_IdAndAccount_UserIdOrderByDateDescIdDesc(tagId, userId);
    }

    @Transactional
    public Transaction createTransaction(Transaction transaction, Long userId) {
        transaction.setId(null); // the id is always generated by the database
        validateAndNormalize(transaction, userId);
        transaction.setTags(resolveTags(transaction.getTagIds()));
        applyEffect(transaction);
        return transactionRepository.save(transaction);
    }

    /** Reverses the balance effect of the old transaction, then applies the new one. All or nothing. */
    @Transactional
    public Transaction updateTransaction(Long id, Transaction details, Long userId) {
        Transaction existing = getTransactionById(id, userId);
        Set<Long> touched = touchedAccounts(existing);
        reverseEffect(existing);

        validateAndNormalize(details, userId);
        existing.setAccountId(details.getAccountId());
        existing.setCategoryId(details.getCategoryId());
        existing.setAmount(details.getAmount());
        existing.setType(details.getType());
        existing.setTargetAccountId(details.getTargetAccountId());
        existing.setDescription(details.getDescription());
        existing.setDate(details.getDate());
        existing.getTags().clear();
        existing.getTags().addAll(resolveTags(details.getTagIds()));

        applyEffect(existing);
        touched.addAll(touchedAccounts(existing));
        ensureNonNegative(touched, "update");
        return transactionRepository.save(existing);
    }

    /** Merges the present fields into the stored transaction and runs the normal update. */
    @Transactional
    public Transaction patchTransaction(Long id, TransactionPatchRequest patch, Long userId) {
        Transaction existing = getTransactionById(id, userId);
        Transaction merged = Transaction.builder()
                .accountId(patch.getAccountId() != null ? patch.getAccountId() : existing.getAccountId())
                .categoryId(patch.getCategoryId() != null ? patch.getCategoryId() : existing.getCategoryId())
                .amount(patch.getAmount() != null ? patch.getAmount() : existing.getAmount())
                .type(patch.getType() != null ? patch.getType() : existing.getType())
                .targetAccountId(patch.getTargetAccountId() != null ? patch.getTargetAccountId() : existing.getTargetAccountId())
                .description(patch.getDescription() != null ? patch.getDescription() : existing.getDescription())
                .date(patch.getDate() != null ? patch.getDate() : existing.getDate())
                .tagIds(patch.getTagIds() != null ? patch.getTagIds()
                        : existing.getTags().stream().map(Tag::getId).toList())
                .build();
        return updateTransaction(id, merged, userId);
    }

    /** Deleting a transaction reverses its effect on the account balance(s). */
    @Transactional
    public void deleteTransaction(Long id, Long userId) {
        Transaction existing = getTransactionById(id, userId);
        reverseEffect(existing);
        ensureNonNegative(touchedAccounts(existing), "delete");
        transactionRepository.delete(existing);
    }

    private Set<Long> touchedAccounts(Transaction tx) {
        Set<Long> ids = new HashSet<>();
        ids.add(tx.getAccountId());
        if (tx.getTargetAccountId() != null) ids.add(tx.getTargetAccountId());
        return ids;
    }

    /** Undoing an income/transfer must not leave an account with a negative balance. */
    private void ensureNonNegative(Set<Long> accountIds, String action) {
        for (Long accountId : accountIds) {
            accountRepository.findById(accountId).ifPresent(account -> {
                if (account.getBalance().signum() < 0) {
                    throw new BadRequestException("Cannot " + action + " this transaction: account "
                            + accountId + " would have a negative balance");
                }
            });
        }
    }

    private Set<Tag> resolveTags(List<Long> tagIds) {
        if (tagIds == null || tagIds.isEmpty()) return new HashSet<>();
        Set<Long> uniqueIds = new LinkedHashSet<>(tagIds);
        Set<Tag> tags = new HashSet<>();
        for (Long tagId : uniqueIds) {
            if (tagId == null) throw new BadRequestException("tagIds must not contain null");
            tags.add(tagRepository.findById(tagId)
                    .orElseThrow(() -> new ResourceNotFoundException("Tag not found: " + tagId)));
        }
        return tags;
    }

    private void requireOwnedAccount(Long accountId, Long userId, String label) {
        Account account = accountRepository.findById(accountId)
                .orElseThrow(() -> new ResourceNotFoundException(label + " not found: " + accountId));
        if (!account.getUserId().equals(userId)) {
            throw new ForbiddenException("You do not have access to " + label.toLowerCase() + " " + accountId);
        }
    }

    private void validateAndNormalize(Transaction tx, Long userId) {
        String type = tx.getType().trim().toUpperCase();
        if (!VALID_TYPES.contains(type)) {
            throw new BadRequestException("Invalid transaction type: " + type);
        }
        tx.setType(type);

        requireOwnedAccount(tx.getAccountId(), userId, "Account");

        if (tx.getCategoryId() != null) {
            Category category = categoryRepository.findById(tx.getCategoryId())
                    .orElseThrow(() -> new ResourceNotFoundException("Category not found: " + tx.getCategoryId()));
            if (type.equals("TRANSFER")) {
                throw new BadRequestException("Transfers cannot have a category");
            }
            if (!category.getType().equals(type)) {
                throw new BadRequestException("Category type " + category.getType()
                        + " does not match transaction type " + type);
            }
        }

        if (type.equals("TRANSFER")) {
            if (tx.getTargetAccountId() == null) {
                throw new BadRequestException("Target account ID is required for transfers");
            }
            if (tx.getTargetAccountId().equals(tx.getAccountId())) {
                throw new BadRequestException("Source and target accounts must be different");
            }
            requireOwnedAccount(tx.getTargetAccountId(), userId, "Target account");
        } else {
            tx.setTargetAccountId(null);
        }
    }

    private void applyEffect(Transaction tx) {
        Account source = accountRepository.findById(tx.getAccountId())
                .orElseThrow(() -> new ResourceNotFoundException("Account not found: " + tx.getAccountId()));

        switch (tx.getType()) {
            case "INCOME" -> source.setBalance(source.getBalance().add(tx.getAmount()));
            case "EXPENSE" -> {
                if (source.getBalance().compareTo(tx.getAmount()) < 0) {
                    throw new BadRequestException("Insufficient balance in account");
                }
                source.setBalance(source.getBalance().subtract(tx.getAmount()));
            }
            case "TRANSFER" -> {
                Account target = accountRepository.findById(tx.getTargetAccountId())
                        .orElseThrow(() -> new ResourceNotFoundException("Target account not found: " + tx.getTargetAccountId()));
                if (source.getBalance().compareTo(tx.getAmount()) < 0) {
                    throw new BadRequestException("Insufficient balance in source account");
                }
                source.setBalance(source.getBalance().subtract(tx.getAmount()));
                target.setBalance(target.getBalance().add(tx.getAmount()));
                accountRepository.save(target);
            }
            default -> throw new BadRequestException("Invalid transaction type: " + tx.getType());
        }
        accountRepository.save(source);
    }

    private void reverseEffect(Transaction tx) {
        Account source = accountRepository.findById(tx.getAccountId())
                .orElseThrow(() -> new ResourceNotFoundException("Account not found: " + tx.getAccountId()));

        switch (tx.getType()) {
            case "INCOME" -> source.setBalance(source.getBalance().subtract(tx.getAmount()));
            case "EXPENSE" -> source.setBalance(source.getBalance().add(tx.getAmount()));
            case "TRANSFER" -> {
                Account target = accountRepository.findById(tx.getTargetAccountId())
                        .orElseThrow(() -> new ResourceNotFoundException("Target account not found: " + tx.getTargetAccountId()));
                source.setBalance(source.getBalance().add(tx.getAmount()));
                target.setBalance(target.getBalance().subtract(tx.getAmount()));
                accountRepository.save(target);
            }
            default -> { }
        }
        accountRepository.save(source);
    }
}
