package com.tengetracker.service;

import com.tengetracker.dto.patch.AccountPatchRequest;
import com.tengetracker.exception.ConflictException;
import com.tengetracker.exception.ForbiddenException;
import com.tengetracker.exception.ResourceNotFoundException;
import com.tengetracker.model.Account;
import com.tengetracker.repository.AccountRepository;
import com.tengetracker.repository.TransactionRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

/** Accounts are private: every method is scoped to the authenticated user's ID. */
@Service
@RequiredArgsConstructor
public class AccountService {
    private final AccountRepository accountRepository;
    private final TransactionRepository transactionRepository;

    public List<Account> getAllAccounts(Long userId) {
        return accountRepository.findByUserIdOrderByIdAsc(userId);
    }

    /** 404 if the account does not exist, 403 if it belongs to another user. */
    public Account getAccountById(Long id, Long userId) {
        Account account = accountRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Account not found with id: " + id));
        if (!account.getUserId().equals(userId)) {
            throw new ForbiddenException("You do not have access to account " + id);
        }
        return account;
    }

    @Transactional
    public Account createAccount(Account account, Long userId) {
        account.setId(null); // the id is always generated by the database
        account.setUserId(userId); // the owner always comes from the JWT, never from the body
        if (account.getCurrency() == null) {
            account.setCurrency("KZT");
        }
        account.setCurrency(account.getCurrency().toUpperCase());
        return accountRepository.save(account);
    }

    @Transactional
    public Account updateAccount(Long id, Account details, Long userId) {
        Account account = getAccountById(id, userId);
        account.setName(details.getName());
        if (details.getCurrency() != null) account.setCurrency(details.getCurrency().toUpperCase());
        return accountRepository.save(account);
    }

    @Transactional
    public Account patchAccount(Long id, AccountPatchRequest patch, Long userId) {
        Account account = getAccountById(id, userId);
        if (patch.getName() != null) account.setName(patch.getName().trim());
        if (patch.getCurrency() != null) account.setCurrency(patch.getCurrency().toUpperCase());
        return accountRepository.save(account);
    }

    @Transactional
    public void deleteAccount(Long id, Long userId) {
        Account account = getAccountById(id, userId);
        if (transactionRepository.existsByAccountIdOrTargetAccountId(id, id)) {
            throw new ConflictException("Account " + id + " has transactions and cannot be deleted. Delete its transactions first.");
        }
        accountRepository.delete(account);
    }
}
