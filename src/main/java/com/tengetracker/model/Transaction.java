package com.tengetracker.model;

import jakarta.persistence.*;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDate;

@Entity
@Table(name = "transactions")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Transaction {

    @Schema(description = "Unique transaction identifier generated by the database", example = "1", accessMode = Schema.AccessMode.READ_ONLY)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Schema(description = "ID of the source account; required for all transaction types", example = "1", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotNull(message = "Account ID is required")
    @Column(name = "account_id", nullable = false)
    private Long accountId;

    @Schema(description = "Optional category identifier associated with the transaction", example = "2", nullable = true)
    @Column(name = "category_id")
    private Long categoryId;

    @Schema(description = "Positive transaction amount in the account currency", example = "1200.00", minimum = "0.01", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotNull(message = "Amount is required")
    @Positive(message = "Amount must be positive")
    @Column(nullable = false, precision = 15, scale = 2)
    private BigDecimal amount;

    @Schema(description = "Transaction operation. INCOME increases the source balance; EXPENSE decreases it; TRANSFER moves funds to targetAccountId.", allowableValues = {"INCOME", "EXPENSE", "TRANSFER"}, example = "EXPENSE", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotNull(message = "Transaction type is required")
    @Column(nullable = false)
    private String type; // INCOME, EXPENSE, TRANSFER

    @Schema(description = "Destination account ID; required when type is TRANSFER and ignored for other types", example = "2", nullable = true)
    @Column(name = "target_account_id")
    private Long targetAccountId;

    @Schema(description = "Optional note explaining the transaction", example = "Groceries", nullable = true)
    private String description;

    @Schema(description = "Transaction date in ISO-8601 format (YYYY-MM-DD)", example = "2026-10-02", type = "string", format = "date", requiredMode = Schema.RequiredMode.REQUIRED)
    @NotNull(message = "Date is required")
    @Column(nullable = false)
    private LocalDate date;
}