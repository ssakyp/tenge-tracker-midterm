package com.tengetracker.controller;

import com.tengetracker.model.Account;
import com.tengetracker.service.AccountService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/accounts")
@RequiredArgsConstructor
@Tag(name = "Accounts", description = "Manage financial accounts. Accounts store a name, current balance, and currency. New accounts default to a balance of 0 and currency KZT when omitted.")
public class AccountController {

    private final AccountService accountService;

    @GetMapping
    @Operation(summary = "List all accounts", description = "Returns every account currently stored in the database. Use this to find account IDs before creating transactions or retrieving/updating a specific account. An empty database returns an empty JSON array.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Accounts retrieved successfully",
                    content = @Content(mediaType = "application/json", schema = @Schema(implementation = Account.class),
                            examples = @ExampleObject(value = "[{\"id\":1,\"name\":\"Main account\",\"balance\":25000.00,\"currency\":\"KZT\"}]")))
    })
    public List<Account> getAllAccounts() {
        return accountService.getAllAccounts();
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get an account by ID", description = "Returns one account by its database ID. The ID is generated by the server when the account is created.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Account found", content = @Content(schema = @Schema(implementation = Account.class))),
            @ApiResponse(responseCode = "404", description = "No account exists with this ID", content = @Content(mediaType = "application/json", examples = @ExampleObject(value = "{\"timestamp\":\"2026-01-01T12:00:00\",\"status\":404,\"error\":\"Account not found with id: 42\"}")))
    })
    public Account getAccountById(@Parameter(description = "ID of the account to retrieve", example = "1", required = true) @PathVariable Long id) {
        return accountService.getAccountById(id);
    }

    @PostMapping
    @Operation(summary = "Create an account", description = "Creates a financial account. The name is required. The ID is generated automatically. Balance defaults to 0 and currency defaults to KZT if not supplied. The balance can be set when creating an account; subsequent PUT updates only the name and currency.")
    @ApiResponses({
            @ApiResponse(responseCode = "201", description = "Account created", content = @Content(schema = @Schema(implementation = Account.class), examples = @ExampleObject(value = "{\"id\":1,\"name\":\"Main account\",\"balance\":25000.00,\"currency\":\"KZT\"}"))),
            @ApiResponse(responseCode = "400", description = "Invalid request: name is blank or validation fails", content = @Content(mediaType = "application/json", examples = @ExampleObject(value = "{\"timestamp\":\"2026-01-01T12:00:00\",\"status\":400,\"errors\":{\"name\":\"Account name is required\"}}")))
    })
    public ResponseEntity<Account> createAccount(
            @io.swagger.v3.oas.annotations.parameters.RequestBody(description = "Account details. Do not include id when creating; the server generates it.", required = true,
                    content = @Content(schema = @Schema(implementation = Account.class), examples = @ExampleObject(value = "{\"name\":\"Main account\",\"balance\":25000.00,\"currency\":\"KZT\"}")))
            @Valid @RequestBody Account account) {
        return new ResponseEntity<>(accountService.createAccount(account), HttpStatus.CREATED);
    }

    @PutMapping("/{id}")
    @Operation(summary = "Update an account", description = "Updates an existing account's name and currency. The balance is not modified by this endpoint. If currency is null or omitted, the current currency is preserved. This operation does not create a new account.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Account updated", content = @Content(schema = @Schema(implementation = Account.class), examples = @ExampleObject(value = "{\"id\":1,\"name\":\"Travel account\",\"balance\":25000.00,\"currency\":\"USD\"}"))),
            @ApiResponse(responseCode = "400", description = "Invalid account data", content = @Content(mediaType = "application/json", examples = @ExampleObject(value = "{\"timestamp\":\"2026-01-01T12:00:00\",\"status\":400,\"errors\":{\"name\":\"Account name is required\"}}"))),
            @ApiResponse(responseCode = "404", description = "Account ID not found", content = @Content(mediaType = "application/json", examples = @ExampleObject(value = "{\"timestamp\":\"2026-01-01T12:00:00\",\"status\":404,\"error\":\"Account not found with id: 42\"}")))
    })
    public Account updateAccount(
            @Parameter(description = "ID of the account to update", example = "1", required = true) @PathVariable Long id,
            @io.swagger.v3.oas.annotations.parameters.RequestBody(description = "New account name and optional currency. Balance is ignored by this update operation.", required = true,
                    content = @Content(schema = @Schema(implementation = Account.class), examples = @ExampleObject(value = "{\"name\":\"Travel account\",\"currency\":\"USD\"}")))
            @Valid @RequestBody Account account) {
        return accountService.updateAccount(id, account);
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete an account", description = "Permanently deletes the account with the supplied ID. A successful deletion returns HTTP 204 with no response body. If the ID does not exist, the API returns 404.")
    @ApiResponses({
            @ApiResponse(responseCode = "204", description = "Account deleted successfully; response body is empty"),
            @ApiResponse(responseCode = "404", description = "Account ID not found", content = @Content(mediaType = "application/json", examples = @ExampleObject(value = "{\"timestamp\":\"2026-01-01T12:00:00\",\"status\":404,\"error\":\"Account not found with id: 42\"}")))
    })
    public ResponseEntity<Void> deleteAccount(@Parameter(description = "ID of the account to delete", example = "1", required = true) @PathVariable Long id) {
        accountService.deleteAccount(id);
        return ResponseEntity.noContent().build();
    }
}
