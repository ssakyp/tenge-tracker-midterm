package com.tengetracker.service;

import com.tengetracker.exception.BadRequestException;
import com.tengetracker.exception.ResourceNotFoundException;
import com.tengetracker.model.Account;
import com.tengetracker.model.Category;
import com.tengetracker.model.Transaction;
import com.tengetracker.repository.AccountRepository;
import com.tengetracker.repository.CategoryRepository;
import com.tengetracker.repository.TransactionRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.util.List;
import java.util.Set;

@Service
@RequiredArgsConstructor
public class TransactionService {

    private static final Set<String> VALID_TYPES = Set.of("INCOME", "EXPENSE", "TRANSFER");

    private final TransactionRepository transactionRepository;
    private final AccountRepository accountRepository;
    private final CategoryRepository categoryRepository;

    public List<Transaction> getAllTransactions(LocalDate startDate, LocalDate endDate, String type) {
        if (startDate != null && endDate != null && startDate.isAfter(endDate)) {
            throw new BadRequestException("startDate must not be after endDate");
        }
        String filterType = null;
        if (type != null) {
            filterType = type.trim().toUpperCase();
            if (!VALID_TYPES.contains(filterType)) {
                throw new BadRequestException("Invalid transaction type: " + type);
            }
        }
        final String typeFilter = filterType;
        return transactionRepository.findAll(Sort.by(Sort.Direction.DESC, "date", "id")).stream()
                .filter(t -> startDate == null || !t.getDate().isBefore(startDate))
                .filter(t -> endDate == null || !t.getDate().isAfter(endDate))
                .filter(t -> typeFilter == null || t.getType().equals(typeFilter))
                .toList();
    }

    public Transaction getTransactionById(Long id) {
        return transactionRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Transaction not found with id: " + id));
    }

    /** Transactions where the account is the source or the transfer target. */
    public List<Transaction> getTransactionsByAccount(Long accountId) {
        if (!accountRepository.existsById(accountId)) {
            throw new ResourceNotFoundException("Account not found with id: " + accountId);
        }
        return transactionRepository.findByAccountIdOrTargetAccountIdOrderByDateDescIdDesc(accountId, accountId);
    }

    public List<Transaction> getTransactionsByCategory(Long categoryId) {
        if (!categoryRepository.existsById(categoryId)) {
            throw new ResourceNotFoundException("Category not found with id: " + categoryId);
        }
        return transactionRepository.findByCategoryIdOrderByDateDescIdDesc(categoryId);
    }

    @Transactional
    public Transaction createTransaction(Transaction transaction) {
        transaction.setId(null); // the id is always generated by the database
        validateAndNormalize(transaction);
        applyEffect(transaction);
        return transactionRepository.save(transaction);
    }

    /** Reverses the balance effect of the old transaction, then applies the new one. All or nothing. */
    @Transactional
    public Transaction updateTransaction(Long id, Transaction details) {
        Transaction existing = getTransactionById(id);
        reverseEffect(existing);

        validateAndNormalize(details);
        existing.setAccountId(details.getAccountId());
        existing.setCategoryId(details.getCategoryId());
        existing.setAmount(details.getAmount());
        existing.setType(details.getType());
        existing.setTargetAccountId(details.getTargetAccountId());
        existing.setDescription(details.getDescription());
        existing.setDate(details.getDate());

        applyEffect(existing);
        return transactionRepository.save(existing);
    }

    /** Deleting a transaction reverses its effect on the account balance(s). */
    @Transactional
    public void deleteTransaction(Long id) {
        Transaction existing = getTransactionById(id);
        reverseEffect(existing);
        transactionRepository.delete(existing);
    }

    private void validateAndNormalize(Transaction tx) {
        String type = tx.getType().trim().toUpperCase();
        if (!VALID_TYPES.contains(type)) {
            throw new BadRequestException("Invalid transaction type: " + type);
        }
        tx.setType(type);

        if (!accountRepository.existsById(tx.getAccountId())) {
            throw new ResourceNotFoundException("Account not found: " + tx.getAccountId());
        }

        if (tx.getCategoryId() != null) {
            Category category = categoryRepository.findById(tx.getCategoryId())
                    .orElseThrow(() -> new ResourceNotFoundException("Category not found: " + tx.getCategoryId()));
            if (type.equals("TRANSFER")) {
                throw new BadRequestException("Transfers cannot have a category");
            }
            if (!category.getType().equals(type)) {
                throw new BadRequestException("Category type " + category.getType()
                        + " does not match transaction type " + type);
            }
        }

        if (type.equals("TRANSFER")) {
            if (tx.getTargetAccountId() == null) {
                throw new BadRequestException("Target account ID is required for transfers");
            }
            if (tx.getTargetAccountId().equals(tx.getAccountId())) {
                throw new BadRequestException("Source and target accounts must be different");
            }
            if (!accountRepository.existsById(tx.getTargetAccountId())) {
                throw new ResourceNotFoundException("Target account not found: " + tx.getTargetAccountId());
            }
        } else {
            tx.setTargetAccountId(null);
        }
    }

    private void applyEffect(Transaction tx) {
        Account source = accountRepository.findById(tx.getAccountId())
                .orElseThrow(() -> new ResourceNotFoundException("Account not found: " + tx.getAccountId()));

        switch (tx.getType()) {
            case "INCOME" -> source.setBalance(source.getBalance().add(tx.getAmount()));
            case "EXPENSE" -> {
                if (source.getBalance().compareTo(tx.getAmount()) < 0) {
                    throw new BadRequestException("Insufficient balance in account");
                }
                source.setBalance(source.getBalance().subtract(tx.getAmount()));
            }
            case "TRANSFER" -> {
                Account target = accountRepository.findById(tx.getTargetAccountId())
                        .orElseThrow(() -> new ResourceNotFoundException("Target account not found: " + tx.getTargetAccountId()));
                if (source.getBalance().compareTo(tx.getAmount()) < 0) {
                    throw new BadRequestException("Insufficient balance in source account");
                }
                source.setBalance(source.getBalance().subtract(tx.getAmount()));
                target.setBalance(target.getBalance().add(tx.getAmount()));
                accountRepository.save(target);
            }
            default -> throw new BadRequestException("Invalid transaction type: " + tx.getType());
        }
        accountRepository.save(source);
    }

    private void reverseEffect(Transaction tx) {
        Account source = accountRepository.findById(tx.getAccountId())
                .orElseThrow(() -> new ResourceNotFoundException("Account not found: " + tx.getAccountId()));

        switch (tx.getType()) {
            case "INCOME" -> source.setBalance(source.getBalance().subtract(tx.getAmount()));
            case "EXPENSE" -> source.setBalance(source.getBalance().add(tx.getAmount()));
            case "TRANSFER" -> {
                Account target = accountRepository.findById(tx.getTargetAccountId())
                        .orElseThrow(() -> new ResourceNotFoundException("Target account not found: " + tx.getTargetAccountId()));
                source.setBalance(source.getBalance().add(tx.getAmount()));
                target.setBalance(target.getBalance().subtract(tx.getAmount()));
                accountRepository.save(target);
            }
            default -> { }
        }
        accountRepository.save(source);
    }
}
