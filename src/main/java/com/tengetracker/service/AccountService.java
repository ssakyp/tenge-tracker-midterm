package com.tengetracker.service;

import com.tengetracker.exception.ConflictException;
import com.tengetracker.exception.ResourceNotFoundException;
import com.tengetracker.model.Account;
import com.tengetracker.repository.AccountRepository;
import com.tengetracker.repository.TransactionRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
@RequiredArgsConstructor
public class AccountService {
    private final AccountRepository accountRepository;
    private final TransactionRepository transactionRepository;

    public List<Account> getAllAccounts() {
        return accountRepository.findAll();
    }

    public Account getAccountById(Long id) {
        return accountRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Account not found with id: " + id));
    }

    @Transactional
    public Account createAccount(Account account) {
        account.setId(null); // the id is always generated by the database
        if (account.getCurrency() == null) {
            account.setCurrency("KZT");
        }
        account.setCurrency(account.getCurrency().toUpperCase());
        return accountRepository.save(account);
    }

    @Transactional
    public Account updateAccount(Long id, Account details) {
        Account account = getAccountById(id);
        account.setName(details.getName());
        if (details.getCurrency() != null) account.setCurrency(details.getCurrency().toUpperCase());
        return accountRepository.save(account);
    }

    @Transactional
    public void deleteAccount(Long id) {
        Account account = getAccountById(id);
        if (transactionRepository.existsByAccountIdOrTargetAccountId(id, id)) {
            throw new ConflictException("Account " + id + " has transactions and cannot be deleted. Delete its transactions first.");
        }
        accountRepository.delete(account);
    }
}
